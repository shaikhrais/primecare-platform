// Compile only the persisted, registered schemas. Never compile user input.
import {readFileSync,writeFileSync} from 'node:fs';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {resolve} from 'node:path';
import Ajv from 'ajv';
import addFormats from 'ajv-formats';
import standalone from 'ajv/dist/standalone/index.js';
import {build} from 'esbuild';

if(process.argv.slice(2).some(arg=>arg!=='--generate')||process.argv.length>3)throw Error('Only --generate or check mode is supported');
execFileSync('python3',['tools/communication-route-bindings.py'],{stdio:'inherit'});
const catalog=JSON.parse(readFileSync('packages/shared/src/communications/registered-contracts.json'));
const ajv=new Ajv({strict:false,code:{source:true}});addFormats(ajv);ajv.addFormat('binary',true);
const exports={};
for(const api of catalog.apis)for(const kind of ['request','response']){
 const name='api'+api.id+'_'+kind;ajv.addSchema(api[kind+'Schema'],name);exports[name]=name;
}
const source=standalone(ajv,exports);
const bundle=await build({stdin:{contents:source,sourcefile:'registered-validators.cjs',resolveDir:process.cwd(),loader:'js'},bundle:true,format:'esm',platform:'neutral',target:'es2022',minify:true,write:false,legalComments:'none'});
const digest=createHash('sha256').update(JSON.stringify(catalog.apis)).digest('hex');
const content='// Generated by tools/communication-schema-validators.mjs; no runtime compiler.\n// Registered API schema source SHA256: '+digest+'\n'+bundle.outputFiles[0].text;
const path=resolve('packages/shared/src/communications/registered-schema-validators.mjs');
if(process.argv.includes('--generate'))writeFileSync(path,content);
else if(readFileSync(path,'utf8')!==content)throw Error('Registered communication validators differ; regenerate explicitly');
console.log('Registered communication validators: '+catalog.apis.length+' APIs, build-time compilation only');
