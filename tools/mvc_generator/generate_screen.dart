import 'dart:io';

bool _validRoute(String route) => route == '/' || RegExp(
  r'^/(?:[A-Za-z0-9_-]+|:[A-Za-z_][A-Za-z0-9_]*)(?:/(?:[A-Za-z0-9_-]+|:[A-Za-z_][A-Za-z0-9_]*))*/?$',
).hasMatch(route);

void main(List<String> args) {
  if (args.isEmpty || args.length < 2) {
    print('Usage: dart generate_screen.dart <AppName> <ScreenName> [RoutePath]');
    print(
      'Example: dart generate_screen.dart primecare_governance ProposalInbox',
    );
    exit(1);
  }

  final appName = args[0];
  final screenName = args[1]; // e.g., ProposalInbox
  if (!RegExp(r'^[a-z][a-z0-9_]*$').hasMatch(appName) ||
      !RegExp(r'^[A-Z][A-Za-z0-9]*$').hasMatch(screenName)) {
    stderr.writeln('Invalid app or screen name.');
    exit(1);
  }

  final snakeCaseName = _toSnakeCase(screenName);
  final route = args.length > 2 ? args[2] : '/generated/$appName/$snakeCaseName';
  if (!_validRoute(route)) {
    stderr.writeln('Invalid route path: $route');
    exit(1);
  }
  final targetDir = Directory('apps/$appName/lib/features/${snakeCaseName}');
  final catalog = File('packages/primecare_ui/lib/src/features/auth/generated_managed_routes.g.dart');
  const header = '// Generated by PrimeCare screen generators. Do not edit by hand.\n'
      '// Registration provides presentation metadata only and never grants access.\n'
      'const generatedManagedScreenRoutes = <String>{\n';
  final existing = catalog.existsSync() ? catalog.readAsStringSync() : '$header};\n';
  if (!existing.startsWith(header) || !existing.endsWith('};\n')) {
    stderr.writeln('Generated route catalog has an unexpected format; no files were changed.');
    exit(1);
  }
  final body = existing.substring(header.length, existing.length - 3);
  final entries = <String>{};
  for (final line in body.split('\n').where((line) => line.isNotEmpty)) {
    final match = RegExp(r"^  '(/[A-Za-z0-9_:/-]*)',$").firstMatch(line);
    if (match == null || !_validRoute(match.group(1)!) || !entries.add(match.group(1)!)) {
      stderr.writeln('Generated route catalog contains invalid or duplicate entries; no files were changed.');
      exit(1);
    }
  }
  if (!entries.add(route)) {
    stderr.writeln('Route is already in the generated catalog: $route');
    exit(1);
  }
  final outputs = [
    File('${targetDir.path}/${snakeCaseName}_model.dart'),
    File('${targetDir.path}/${snakeCaseName}_controller.dart'),
    File('${targetDir.path}/${snakeCaseName}_view.dart'),
  ];
  if (outputs.any((file) => file.existsSync())) {
    stderr.writeln('A generated screen file already exists; no files were changed.');
    exit(1);
  }

  if (!targetDir.existsSync()) {
    targetDir.createSync(recursive: true);
  }

  // Generate Model
  final modelFile = File('${targetDir.path}/${snakeCaseName}_model.dart');
  modelFile.writeAsStringSync(_generateModelContent(screenName));

  // Generate Controller
  final controllerFile = File(
    '${targetDir.path}/${snakeCaseName}_controller.dart',
  );
  controllerFile.writeAsStringSync(
    _generateControllerContent(screenName, snakeCaseName),
  );

  // Generate View
  final viewFile = File('${targetDir.path}/${snakeCaseName}_view.dart');
  viewFile.writeAsStringSync(_generateViewContent(screenName, snakeCaseName));
  final sorted = entries.toList()..sort();
  catalog.parent.createSync(recursive: true);
  catalog.writeAsStringSync('$header${sorted.map((entry) => "  '$entry',\n").join()}};\n');

  print(
    'Successfully generated MVC structure for $screenName in apps/$appName/lib/features/$snakeCaseName',
  );
  print('Registered presentation route $route. Add it to the owning application module and authorization policy before routing to this view.');
}

String _toSnakeCase(String input) {
  return input.replaceAllMapped(RegExp(r'[A-Z]'), (Match m) {
    return m.start == 0 ? m[0]!.toLowerCase() : '_${m[0]!.toLowerCase()}';
  });
}

String _generateModelContent(String screenName) {
  return '''
class ${screenName}Model {
  final bool isLoading;
  final String? error;
  // Add more state fields here

  const ${screenName}Model({
    this.isLoading = false,
    this.error,
  });

  ${screenName}Model copyWith({
    bool? isLoading,
    String? error,
  }) {
    return ${screenName}Model(
      isLoading: isLoading ?? this.isLoading,
      error: error ?? this.error,
    );
  }
}
''';
}

String _generateControllerContent(String screenName, String snakeCaseName) {
  final lowerCamel = screenName[0].toLowerCase() + screenName.substring(1);
  return '''
import 'package:flutter_riverpod/legacy.dart';
import '${snakeCaseName}_model.dart';

final ${lowerCamel}ControllerProvider = StateNotifierProvider<${screenName}Controller, ${screenName}Model>((ref) {
  return ${screenName}Controller();
});

class ${screenName}Controller extends StateNotifier<${screenName}Model> {
  ${screenName}Controller() : super(const ${screenName}Model()) {
    _init();
  }

  Future<void> _init() async {
    state = state.copyWith(isLoading: true);
    try {
      // Simulate API call
      await Future<void>.delayed(const Duration(seconds: 1));
      state = state.copyWith(isLoading: false);
    } catch (e) {
      state = state.copyWith(isLoading: false, error: e.toString());
    }
  }

  // Add business logic methods here
}
''';
}

String _generateViewContent(String screenName, String snakeCaseName) {
  final lowerCamel = screenName[0].toLowerCase() + screenName.substring(1);
  return '''
import 'package:primecare_ui/primecare_ui.dart';
import '${snakeCaseName}_controller.dart';

// Presentation registration is generated centrally; the owning application must wire and authorize the route.
class ${screenName}View extends GovernedConsumerWidget {
  const ${screenName}View({super.key});

  @override
  Widget buildScreen(BuildContext context, WidgetRef ref) {
    final theme = context.theme;
    final state = ref.watch(${lowerCamel}ControllerProvider);

    return Scaffold(
      backgroundColor: theme.colors.surfaceContainerLowest,
      appBar: AppBar(
        title: Text('$screenName'),
        backgroundColor: theme.colors.surface,
        elevation: 0,
      ),
      body: _buildBody(context, state, theme),
    );
  }

  Widget _buildBody(BuildContext context, dynamic state, PrimeThemeData theme) {
    if (state.isLoading) {
      return Center(child: CircularProgressIndicator(color: theme.colors.primary));
    }

    if (state.error != null) {
      return Center(
        child: Text(
          state.error!,
          style: theme.typography.bodyLarge.copyWith(color: theme.colors.error),
        ),
      );
    }

    return Padding(
      padding: const EdgeInsets.all(24.0),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Text(
            'Welcome to $screenName',
            style: theme.typography.h2,
          ),
          const SizedBox(height: 16),
          // Content goes here
        ],
      ),
    );
  }
}
''';
}
