import assert from 'node:assert/strict';
import pg from 'pg';
import {registerThemeMigrationControls} from './theme-migration-registration.mjs';
const url=new URL(process.env.THEME_MIGRATION_TEST_URL);
if(url.hostname!=='127.0.0.1'||url.pathname!=='/theme_migration_test')throw Error('Dedicated loopback database required');
const db=new pg.Client({connectionString:url.href});await db.connect();
const schema='governance_'+ 'a'.repeat(40), t=n=>'"'+schema+'"."govt_'+n+'"';
try{
 await db.query(`CREATE SCHEMA "${schema}";
 CREATE TABLE ${t('source_manifest')}(manifest_sha256 text);
 CREATE TABLE ${t('screens')}(id bigint,screen_code text,route_path text,active int);
 CREATE TABLE ${t('roles')}(id bigint,role_code text,active int);
 CREATE TABLE ${t('role_screen_permissions')}(screen_id bigint,role_id bigint,can_view int);
 CREATE TABLE ${t('api_endpoints')}(id bigint,route_path text);
 CREATE TABLE ${t('api_permissions')}(role_id bigint,api_id bigint,can_access int,permission_key text);
 CREATE TABLE ${t('screen_api_links')}(screen_id bigint,api_id bigint);
 CREATE TABLE ${t('languages')}(language_id bigint,language_code text,enabled int);
 CREATE TABLE ${t('screen_components')}(_primecare_import_row bigint,id bigint,screen_id bigint,component_code text,component_name text,component_type text,data_cy text,file_path text,implementation_status text);
 CREATE TABLE ${t('screen_required_elements')}(_primecare_import_row bigint,id bigint,screen_id bigint,element_key text,element_type text,label text,test_id text,required int);
 CREATE TABLE ${t('language_resources')}(_primecare_import_row bigint,resource_id bigint,resource_key text,resource_group text,description text,context text,active int);
 CREATE TABLE ${t('language_resource_values')}(_primecare_import_row bigint,translation_id bigint,resource_id bigint,language_id bigint,translated_text text,reviewed int,approved int,version text);
 INSERT INTO ${t('source_manifest')} VALUES('fixture');
 INSERT INTO ${t('screens')} VALUES(2534,'tenant_admin_command_center','/tenant-dashboard',1);
 INSERT INTO ${t('roles')} VALUES(72,'tenant_admin',1);
 INSERT INTO ${t('role_screen_permissions')} VALUES(2534,72,1);
 INSERT INTO ${t('api_endpoints')} VALUES(777,'/v1/user/preferences');
 INSERT INTO ${t('api_permissions')} VALUES(72,777,1,'authenticated_self_preferences');
 INSERT INTO ${t('screen_api_links')} VALUES(2534,777);
 INSERT INTO ${t('languages')} VALUES(1,'en',1),(2,'fr',1),(3,'es',1);`);
 assert.deepEqual(await registerThemeMigrationControls(db,schema,'fixture'),{controls:3,translations:9,committed:false});
 assert.equal(Number((await db.query('SELECT count(*) n FROM '+t('screen_components'))).rows[0].n),0);
 await assert.rejects(registerThemeMigrationControls(db,schema,'fixture',{requireExisting:true}),/Missing registered/);
 assert.deepEqual(await registerThemeMigrationControls(db,schema,'fixture',{apply:true}),{controls:3,translations:9,committed:true});
 assert.deepEqual(await registerThemeMigrationControls(db,schema,'fixture',{requireExisting:true}),{controls:3,translations:9,committed:false});
 assert.equal(Number((await db.query('SELECT count(*) n FROM '+t('screen_components'))).rows[0].n),3);
 assert.equal(Number((await db.query('SELECT count(*) n FROM '+t('language_resource_values'))).rows[0].n),9);
 await db.query('UPDATE '+t('role_screen_permissions')+' SET can_view=0');
 await assert.rejects(registerThemeMigrationControls(db,schema,'fixture',{apply:true}),/Host authority/);
 assert.equal(Number((await db.query('SELECT count(*) n FROM '+t('screen_components'))).rows[0].n),3);
 await db.query('UPDATE '+t('role_screen_permissions')+' SET can_view=1');
 await db.query("UPDATE "+t('screen_components')+" SET component_name='conflict' WHERE data_cy='theme-migration-save'");
 await assert.rejects(registerThemeMigrationControls(db,schema,'fixture',{apply:true}),/Existing metadata differs/);
 assert.equal(Number((await db.query('SELECT count(*) n FROM '+t('language_resource_values'))).rows[0].n),9);
 console.log('Isolated registration, replay and fail-closed checks passed.');
}finally{await db.end();}
