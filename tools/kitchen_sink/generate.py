"""Generate developer examples from existing PrimeCare registrations and audit mappings."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PACKAGE = ROOT / 'packages/primecare_kitchen_sink_catalog'


def generate(check=False):
    read = lambda name: json.loads((ROOT / name).read_text())
    registrations = {name: read(f'packages/primecare_ui/catalogs/{name}.registration.json')
                     for name in ('component-catalogue', 'data-controls', 'dashboard-widgets')}
    proposal = read('packages/primecare_ui/catalogs/developer-catalogue.json')
    mappings = {row['id']: row for row in read('scripts/shared-skeleton-equivalents.json')}
    stories = []
    groups = {
        'actions': ['button', 'menu', 'tooltip'],
        'forms': ['input', 'multiline', 'select', 'checkbox', 'switch', 'radio', 'form'],
        'content': ['card', 'badge', 'tabs', 'accordion', 'code', 'preview'],
        'overlays': ['dialog', 'drawer', 'toast'],
        'feedback': ['loading', 'splash', 'empty', 'error', 'countdown', 'async'],
        'data': ['table', 'date', 'time', 'number', 'mask', 'autocomplete'],
        'charts': ['line', 'area', 'bar', 'donut', 'metric'],
    }
    apis = {'input': 'field', 'multiline': 'field', 'checkbox': 'boolean', 'switch': 'boolean',
            'dialog': 'modal', 'drawer': 'modal', 'toast': 'feedback', 'async': 'asyncRegion',
            'loading': 'state', 'splash': 'state', 'empty': 'state', 'error': 'state',
            'line': 'chart', 'area': 'chart', 'bar': 'chart', 'donut': 'chart',
            'date': 'field', 'time': 'field', 'number': 'field', 'mask': 'field'}
    for group, ids in groups.items():
        family = 'data-controls' if group == 'data' else 'dashboard-widgets' if group == 'charts' else 'component-catalogue'
        for identity in ids:
            key = 'loading' if identity == 'async' else 'chart' if identity in ['line', 'area', 'bar', 'donut'] else identity
            api = apis.get(identity, identity)
            flutter_symbol = {'countdown':'PrimeCountdown', 'code':'PrimeCodePreview', 'async':'PrimeAsyncBoundary',
                              'dialog':'PrimeCatalogueModal', 'drawer':'PrimeCatalogueModal', 'table':'PrimeVirtualTable',
                              'autocomplete':'web-only', 'metric':'web-only'}.get(identity,
                              'PrimeChart' if api == 'chart' else 'PrimeDataKit.field' if group == 'data' else 'PrimeComponentKit.' + api)
            stories.append({'id': identity, 'category': group, 'family': family,
                'titles': {locale: registrations[family]['locales'][locale][key]
                           + (f' · {identity}' if api == 'chart' else '') for locale in ['en', 'fr', 'es']},
                'owner': 'packages/primecare_ui', 'webSource': f'packages/primecare_ui/web/{family}.ts',
                'webSymbol': ('PrimeDataControls' if family == 'data-controls' else
                              'PrimeDashboardWidgets' if family == 'dashboard-widgets' else 'PrimeComponentFactory') + '.' + api,
                'flutterSymbol': flutter_symbol, 'flutterOwner': 'packages/flutter_core',
                'flutterSource': f'packages/flutter_core/lib/{family.replace("-", "_")}.dart',
                'webPreview': True, 'flutterPreview': identity not in ['autocomplete', 'metric'],
                'exampleKind': 'local-synthetic', 'productionAcceptance': 'not-inferred'})
    catalog = {'schemaVersion': 1, 'previewOnly': True, 'vendorSourceCopied': False,
        'fullReferenceParity': False, 'labels': read('packages/primecare_kitchen_sink_catalog/labels.json'), 'stories': stories,
        'references': [{'id': feature['id'], 'recordedDisposition': feature['disposition'],
                        'mapped': feature['id'] in mappings,
                        'web': mappings.get(feature['id'], {}).get('web', {}).get('entry'),
                        'flutter': mappings.get(feature['id'], {}).get('native', {}).get('entry'),
                        'scope': mappings.get(feature['id'], {}).get('scope', feature.get('reason', ''))}
                       for feature in proposal['features']],
        'sources': {p: hashlib.sha256((ROOT / p).read_bytes()).hexdigest() for p in [
            'packages/primecare_ui/catalogs/developer-catalogue.json',
            'scripts/shared-skeleton-equivalents.json',
            *[f'packages/primecare_ui/catalogs/{name}.registration.json' for name in registrations]]}}
    outputs = {PACKAGE / 'catalog.json': json.dumps(catalog, indent=2, ensure_ascii=False) + '\n'}
    for name, value in registrations.items():
        outputs[PACKAGE / f'metadata/{name}.json'] = json.dumps(value, indent=2, ensure_ascii=False) + '\n'
    # Generated snapshots retain the existing control IDs and labels; no new grants or registrations.
    dart = "// Generated by tools/kitchen_sink/generate.py. Do not edit.\nimport 'dart:convert';\n"
    for name, value in [('kitchenSinkCatalog', catalog),
                        *[(name.replace('-', '_') + 'Metadata', value) for name, value in registrations.items()]]:
        raw = json.dumps(value, ensure_ascii=False, separators=(',', ':'))
        assert "'''" not in raw
        dart += f"final Map<String, dynamic> {name} = jsonDecode(r'''{raw}''') as Map<String, dynamic>;\n"
    outputs[PACKAGE / 'lib/primecare_kitchen_sink_catalog.dart'] = dart
    for path, content in outputs.items():
        if check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit('Kitchen sink catalog drift: ' + str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print(json.dumps({'stories': len(stories), 'referenceMappings': len(catalog['references']), 'checked': check}))


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    generate(parser.parse_args().check)
