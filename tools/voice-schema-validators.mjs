// Build-time validation of the independently verified native voice contracts.
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import Ajv from 'ajv';
import standalone from 'ajv/dist/standalone/index.js';
import {build} from 'esbuild';
if(process.argv.slice(2).some(x=>x!=='--generate')||process.argv.length>3)throw Error('Explicit generation or check required');
const definition=JSON.parse(readFileSync('tools/governance-production/twilio-contracts-registration.json','utf8'));
const contacts=JSON.parse(readFileSync('tools/governance-production/voice-contact-contracts-registration.json','utf8'));
const native=[...definition.operations.filter(op=>op.authentication==='native-session-csrf'),...contacts.operations];
if(native.length!==12)throw Error('Exact registered native voice contracts required');
const ajv=new Ajv({strict:false,code:{source:true}}),exports={};
ajv.addFormat('uuid',/^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$/i);
for(const [index,op] of native.entries())for(const kind of ['request','response']){
 const key='voice'+index+'_'+kind;ajv.addSchema(op[kind],key);exports[key]=key;
}
const source=standalone(ajv,exports);
const bundle=await build({stdin:{contents:source,resolveDir:process.cwd(),loader:'js'},bundle:true,format:'esm',platform:'neutral',target:'es2022',minify:true,write:false,legalComments:'none'});
const digest=createHash('sha256').update(JSON.stringify(native)).digest('hex');
const content='// Generated by tools/voice-schema-validators.mjs; no runtime compiler.\n// Native voice schema SHA256: '+digest+'\n'+bundle.outputFiles[0].text;
const path='packages/shared/src/communications/voice-schema-validators.mjs';
if(process.argv.includes('--generate'))writeFileSync(path,content);
else if(readFileSync(path,'utf8')!==content)throw Error('Native voice validators differ; regenerate explicitly');
console.log('Native voice validators checked: '+native.length+' contracts');
