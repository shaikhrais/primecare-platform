"""Integrate only recognizable generated dashboard placeholders; no DB writes."""
import argparse
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DIRECTORY = Path('packages/primecare_ui/lib/src/features/generated_screens')
FIXTURE = Path('packages/primecare_ui/test/fixtures/role_dashboard_entries.dart')


def classify(screen, source):
    if source is None:
        return 'missing', None
    classes = re.findall(r'class ([A-Z][A-Za-z0-9_]*) extends ', source)
    if len(classes) != 1:
        return 'preserved', None
    if 'extends GovernedWorkspaceEntry' in source:
        if re.search(r"super\(route:\s*'" + re.escape(screen['route']) + r"'\)", source):
            return 'shared', classes[0]
        return 'preserved', None
    markers = ['// Generated directly from SQLite Database', "'100% READY'",
               'GOVERNANCE SPECIFICATIONS & ALL API ENDPOINTS', 'onPressed: () {}',
               'extends GovernedConsumerWidget', "'status': 'success'"]
    if not source.startswith(markers[0]) or not all(marker in source for marker in markers):
        return 'preserved', None
    # Leave any non-template action implementation intact for individual review.
    without_empty = source.replace('onPressed: () {}', '')
    if 'onPressed:' in without_empty:
        return 'preserved', None
    return 'template', classes[0]


def wrapper(screen, name):
    if not re.fullmatch(r'[a-z][a-z0-9_]*', screen['code']) or not re.fullmatch(r'/[A-Za-z0-9_./:-]+', screen['route']):
        raise ValueError('Invalid registered dashboard identity')
    return ("// Existing registered entry; domain actions remain subject to their own contracts.\n"
            "import '../workspace/governed_workspace_screen.dart';\n\n"
            f"class {name} extends GovernedWorkspaceEntry {{\n"
            f"  const {name}({{super.key}})\n"
            f"      : super(route: '{screen['route']}');\n}}\n")


def make_plan(registry, sources, referenced=()):
    identities = set()
    plan = []
    for screen in registry['screens']:
        if screen['renderer'] != 'dashboard':
            continue
        if screen['code'] in identities:
            raise ValueError('Duplicate dashboard code')
        identities.add(screen['code'])
        source = sources.get(screen['code'])
        status, name = classify(screen, source)
        if status == 'template' and screen['code'] in referenced:
            status, name = 'referenced-provider', None
        plan.append({'id': screen['id'], 'code': screen['code'], 'route': screen['route'],
                     'status': status, 'class': name})
    return plan


def external_references(sources):
    providers = {name: code for code, source in sources.items() if source for name in
                 re.findall(r'final (\w+DataProvider)\s*=', source)}
    if not providers:
        return set()
    expression = r'\b(?:' + '|'.join(re.escape(name) for name in providers) + r')\b'
    result = subprocess.run(['rg', '-l', expression, 'packages', 'apps', '--glob', '*.dart'],
                            cwd=ROOT, capture_output=True, text=True)
    if result.returncode not in (0, 1):
        raise RuntimeError('Reference inventory failed')
    blocked = set()
    for name in result.stdout.splitlines():
        text = (ROOT / name).read_text()
        for match in re.finditer(expression, text):
            code = providers[match.group()]
            if Path(name) != DIRECTORY / (code + '.dart'):
                blocked.add(code)
    return blocked


def fixture(plan):
    entries = [row for row in plan if row['status'] in ('shared', 'template')]
    lines = ['// Generated by tools/integrate-role-dashboards.py; registry routes only.',
             "import 'package:primecare_ui/src/features/workspace/governed_workspace_screen.dart';"]
    for index, row in enumerate(entries):
        lines.append(f"import 'package:primecare_ui/src/features/generated_screens/{row['code']}.dart' as entry{index};")
    lines.append('final registeredDashboardEntries = <GovernedWorkspaceEntry>[')
    lines.extend(f"  const entry{index}.{row['class']}()," for index, row in enumerate(entries))
    lines.append('];')
    lines.append('const registeredDashboardRoutes = <String>[')
    lines.extend(f"  '{row['route']}'," for row in entries)
    lines.append('];')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--apply', action='store_true')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    registry = json.loads((ROOT / 'cloudflare/workers/src/workspace-registry.json').read_text())
    sources = {screen['code']: path.read_text() if path.is_file() else None
               for screen in registry['screens'] if screen['renderer'] == 'dashboard'
               for path in [ROOT / DIRECTORY / (screen['code'] + '.dart')]}
    plan = make_plan(registry, sources, external_references(sources))
    changes = [row for row in plan if row['status'] == 'template']
    if args.apply:
        for row in changes:
            (ROOT / DIRECTORY / (row['code'] + '.dart')).write_text(wrapper(row, row['class']))
        (ROOT / FIXTURE).write_text(fixture(plan))
    if args.check:
        if changes or (ROOT / FIXTURE).read_text() != fixture(plan):
            raise SystemExit('Dashboard integration or fixture is out of date')
    print(json.dumps({'changes': len(changes), 'statusCounts': {status: sum(row['status'] == status for row in plan)
          for status in sorted({row['status'] for row in plan})},
          'preserved': [row['code'] for row in plan if row['status'] not in ('shared', 'template')]}, indent=2))
