import 'dart:io';

void main() {
  final inventoryFile = File('.agents/governance/page_inventory.yaml');
  if (!inventoryFile.existsSync()) {
    print('Failed to open page_inventory.yaml');
    exit(1);
  }

  final String yaml = inventoryFile.readAsStringSync();
  final Map<String, List<Map<String, String>>> roleMenus = {};
  final List<Map<String, String>> globalItems = [];

  final blocks = yaml.split(RegExp(r'\n\s*-\s+id:'));
  // Skips the first header block

  for (int i = 1; i < blocks.length; i++) {
    final block = blocks[i];

    final labelMatch = RegExp(r'label:\s*"([^"]+)"').firstMatch(block);
    final routeVarMatch = RegExp(r'route_var:\s*"([^"]+)"').firstMatch(block);
    final iconVarMatch = RegExp(r'icon_var:\s*"([^"]+)"').firstMatch(block);
    final sectionMatch = RegExp(r'section:\s*"([^"]+)"').firstMatch(block);
    final rolesMatch = RegExp(r'role_allowed:\s*\[(.*?)\]').firstMatch(block);

    if (labelMatch != null &&
        routeVarMatch != null &&
        iconVarMatch != null &&
        rolesMatch != null) {
      final label = labelMatch.group(1)!;
      final routeVar = routeVarMatch.group(1)!;
      final iconVar = iconVarMatch.group(1)!;
      final section = sectionMatch?.group(1) ?? 'Main';

      final rolesRaw = rolesMatch.group(1)!;
      final roles = rolesRaw
          .split(',')
          .map((s) => s.trim().replaceAll('"', ''))
          .where((s) => s.isNotEmpty)
          .toList();

      final item = {
        'id': labelMatch
            .group(1)!
            .toLowerCase()
            .replaceAll(
              ' ',
              '_',
            ), // Fallback if id missing, but we'll use id if available
        'label': label,
        'route_var': routeVar,
        'icon_var': iconVar,
        'section': section,
      };

      // Extract ID if explicitly present in the block
      final idMatch = RegExp(r'id:\s*"([^"]+)"').firstMatch(block);
      if (idMatch != null) {
        item['id'] = idMatch.group(1)!;
      }

      if (roles.contains('all') || roles.contains('*')) {
        globalItems.add(item);
      } else {
        for (final role in roles) {
          if (!roleMenus.containsKey(role)) {
            roleMenus[role] = [];
          }
          roleMenus[role]!.add(item);
        }
      }
    }
  }

  // Inject global items into all roles
  for (final role in roleMenus.keys) {
    roleMenus[role]!.addAll(globalItems);
  }

  final buffer = StringBuffer();
  buffer.writeln('// Layer: 01_INFRASTRUCTURE');
  buffer.writeln('// GENERATED CODE - DO NOT MODIFY BY HAND');
  buffer.writeln(
    '// This file is generated by .agents/governance/manifest_generator.dart',
  );
  buffer.writeln('// Source: .agents/governance/page_inventory.yaml');
  buffer.writeln();
  buffer.writeln("import 'package:lucide_icons/lucide_icons.dart';");
  buffer.writeln("import '../models/01_I_navigation_item.dart';");
  buffer.writeln("import '../routes/groups/01_I_corporate_routes.dart';");
  buffer.writeln("import '../routes/groups/01_I_franchise_routes.dart';");
  buffer.writeln("import '../routes/groups/01_I_clinical_routes.dart';");
  buffer.writeln("import '../routes/groups/01_I_client_routes.dart';");
  buffer.writeln("import '../routes/groups/01_I_common_routes.dart';");
  buffer.writeln();
  buffer.writeln('class NavigationRegistry {');
  buffer.writeln(
    '  static final Map<String, List<PrimeCareNavigationItem>> _roleMenus = {',
  );

  for (final role in roleMenus.keys) {
    buffer.writeln("    '$role': [");
    for (final item in roleMenus[role]!) {
      final sectionKey = item['section']!.toLowerCase().replaceAll(' ', '_');
      buffer.writeln('      const PrimeCareNavigationItem(');
      buffer.writeln("        label: 'navigation.items.${item['id']}',");
      buffer.writeln("        icon: ${item['icon_var']},");
      buffer.writeln("        route: ${item['route_var']},");
      buffer.writeln("        section: 'navigation.sections.$sectionKey',");
      buffer.writeln('      ),');
    }
    buffer.writeln('    ],');
  }

  buffer.writeln('  };');
  buffer.writeln();
  buffer.writeln('''
  static List<PrimeCareNavigationItem> getMenuForRole(String role) {
    // 1. Super Admin / Admin master directory fallback
    final checkRole = role.toLowerCase();
    if (checkRole == 'super admin' ||
        checkRole == 'admin' ||
        checkRole == 'it admin') {
      final Map<String, PrimeCareNavigationItem> allItems = {};
      _roleMenus.forEach((roleName, menuList) {
        for (final item in menuList) {
          if (!allItems.containsKey(item.route)) {
            allItems[item.route] = PrimeCareNavigationItem(
              label: item.label,
              icon: item.icon,
              route: item.route,
              section: item.section ?? 'Master Directory',
              activeIcon: item.activeIcon,
            );
          }
        }
      });
      return allItems.values.toList();
    }

    // 2. Try exact match first
    if (_roleMenus.containsKey(role)) {
      return _roleMenus[role]!;
    }

    // 3. Try case-insensitive exact match
    final upperRole = role.toUpperCase();
    for (var key in _roleMenus.keys) {
      if (key.toUpperCase() == upperRole) {
        return _roleMenus[key]!;
      }
    }

    // 4. Fallback to Title Case normalization
    final normalizedRole = role
        .split(' ')
        .map(
          (word) => word.isEmpty
              ? ''
              : '\${word[0].toUpperCase()}\${word.substring(1).toLowerCase()}',
        )
        .join(' ');

    return _roleMenus[normalizedRole] ?? _roleMenus['Admin'] ?? [];
  }
}''');

  final outputFile = File(
    'packages/flutter_core/lib/config/01_I_navigation_registry.dart',
  );
  outputFile.writeAsStringSync(buffer.toString());
  print(
    '✅ Successfully generated navigation_registry.dart with \${roleMenus.length} roles and \${roleMenus.values.expand((l) => l).length} total route mappings!',
  );
}
