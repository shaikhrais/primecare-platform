enum ResolutionTier {
  /// Mobile (< 600px)
  mob,

  /// Tablet (600px - 1024px)
  tab,

  /// Full HD / Industry Standard Desktop (1024px - 1440px)
  oneK,

  /// Quad HD / High Density Desktop (1440px - 2560px)
  twoK,

  /// Ultra High Density (2560px - 3840px)
  threeK,

  /// 4K resolution (>= 3840px)
  fourK,

  /// Wall-sized / Digital Signage / Institutional display (75"-100"+)
  mega,
}
