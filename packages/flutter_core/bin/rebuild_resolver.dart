import 'dart:io';

void main() {
  final packageRoot = Directory.current.path;
  final projectRoot = Directory(packageRoot).parent.parent.path;
  final adaptersSrc = '$projectRoot/packages/primecare_adapters/lib/src';
  final resolverFile = '$packageRoot/lib/01_I_dynamic_adapter_resolver.dart';

  // 1. Find all adapters and extract provider names
  final adapterFiles = Directory(adaptersSrc)
      .listSync(recursive: true)
      .where((f) => f.path.endsWith('_adapter.dart'))
      .toList();

  final Map<String, String> registryEntries = {};
  
  for (final file in adapterFiles) {
    final content = File(file.path).readAsStringSync();
    final match = RegExp(r'final\s+(\w+Provider)\s*=').firstMatch(content);
    if (match != null) {
      final fileName = file.path.split(Platform.pathSeparator).last;
      final role = fileName.replaceAll('04_A_', '').replaceAll('_dashboard_adapter.dart', '').replaceAll('_adapter.dart', '');
      
      if (role == 'dynamic' || role == 'primecare_form') continue;
      
      final camelKey = _toCamel(role) + (fileName.contains('dashboard') ? 'Dashboard' : '');
      registryEntries[camelKey] = match.group(1)!;
    }
  }

  // Also include form adapters
  final formFiles = Directory(packageRoot + '/lib/features')
      .listSync(recursive: true)
      .where((f) => f.path.endsWith('_adapter.dart'))
      .toList();

  for (final file in formFiles) {
     final content = File(file.path).readAsStringSync();
     final match = RegExp(r'final\s+(\w+Provider)\s*=').firstMatch(content);
     if (match != null) {
        final fileName = file.path.split(Platform.pathSeparator).last;
        final role = fileName.replaceAll('01_I_', '').replaceAll('_adapter.dart', '');
        final camelKey = _toCamel(role);
        registryEntries[camelKey] = match.group(1)!;
     }
  }

  final sortedKeys = registryEntries.keys.toList()..sort();

  final buffer = StringBuffer();
  buffer.writeln('// Layer: 01_INFRASTRUCTURE');
  buffer.writeln('// DYNAMIC ADAPTER RESOLVER');
  buffer.writeln('// Auto-generated by PrimeCare UI Architectural Normalize Pipeline');
  buffer.writeln('');
  buffer.writeln('import \'package:primecare_ui/primecare_ui.dart\';');
  buffer.writeln('');
  buffer.writeln('/// Global Registry dynamically mapping screen routing IDs to their Hydration Adapters');
  buffer.writeln('final Map<String, dynamic> globalAdapterRegistry = {');
  
  for (final key in sortedKeys) {
    buffer.writeln('  \'$key\': ${registryEntries[key]},');
  }
  
  buffer.writeln('};');
  buffer.writeln('');
  buffer.writeln('/// Resolver utility to dynamically fetch any ViewModel provider by string ref');
  buffer.writeln('dynamic resolveAdapterByName(String name) {');
  buffer.writeln('  return globalAdapterRegistry[name];');
  buffer.writeln('}');
  buffer.writeln('');

  File(resolverFile).writeAsStringSync(buffer.toString());
  print('Resolver updated with ${registryEntries.length} entries.');
}

String _toCamel(String s) {
  final parts = s.split('_');
  return parts[0] + parts.skip(1).map((p) => p[0].toUpperCase() + p.substring(1)).join('');
}
