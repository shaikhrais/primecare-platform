class FeatureDto {
  final Map<String, dynamic> rawJson;

  FeatureDto(this.rawJson);

  factory FeatureDto.fromJson(Map<String, dynamic> json) {
    return FeatureDto(json);
  }

  String get id => rawJson['id']?.toString() ?? 'SYS-UNK';
  String get title => rawJson['title']?.toString() ?? 'Record Data';
  String get status => rawJson['status']?.toString() ?? 'Active';
  String get description => rawJson['description']?.toString() ?? 'Autogenerated block from UI engine.';
  String get type => rawJson['type']?.toString() ?? 'UNKNOWN';
}
