        for (const [code, assocs] of Object.entries(registry)) {
            for (const a of assocs) {
                if (registry[a] && !registry[a].includes(code)) {
                    broken.push(code + ' → ' + a + ' (missing reverse)');
                }
            }
        }
        // Allow some one-way links — just report them
        if (broken.length > 0) {
            console.warn('One-way associate links:', broken.slice(0, 10));
        }
