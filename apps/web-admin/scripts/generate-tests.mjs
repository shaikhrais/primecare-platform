// ── Read MASTER_REGISTRY directly from the TS source ──────────────────
function parseMasterRegistry() {
    const registryPath = path.resolve(ROOT, '../../packages/shared/src/registries/PageRegistry/master-registry.ts');
    const content = fs.readFileSync(registryPath, 'utf-8');

    const entries = {};
    // Match patterns like: CODE: { file: '...', label: '...', type: '...', owner: '...', associates: [...] },
    const regex = /^\s*(\w+):\s*\{\s*file:\s*'([^']+)',\s*label:\s*'([^']+)',\s*type:\s*'([^']+)',\s*owner:\s*'([^']+)',\s*associates:\s*\[([^\]]*)\]/gm;
    let match;
    while ((match = regex.exec(content)) !== null) {
        const [, code, file, label, type, owner, assocStr] = match;
        const associates = assocStr
            .split(',')
            .map(s => s.trim().replace(/'/g, ''))
            .filter(Boolean);
        entries[code] = { file, label, type, owner, associates };
    }
    return entries;
}

// ── Scan a .tsx file for data-cy attribute values ──────────────────────
function scanDataCy(filePath) {
    try {
        const content = fs.readFileSync(filePath, 'utf-8');
        const matches = [];
        const regex = /data-cy=["'`{]"?([^"'`}]+)"?["'`}]/g;
        let m;
        while ((m = regex.exec(content)) !== null) {
            const val = m[1].trim();
            // Filter out JS expressions picked up from template literal data-cy attrs
            if (!val.includes(' ') && !val.includes('=') && !val.includes('(') && val.length < 80) {
                matches.push(val);
            }
        }
        return { content, dataCy: matches };
    } catch {
        return { content: '', dataCy: [] };
    }
}

// ── Recursively find all .tsx files ───────────────────────────────────
function findTsxFiles(dir) {
    const results = [];
    if (!fs.existsSync(dir)) return results;
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
        const full = path.join(dir, entry.name);
        if (entry.isDirectory()) results.push(...findTsxFiles(full));
        else if (entry.name.endsWith('.tsx')) results.push(full);
    }
    return results;
}

// ── Convert file path to import alias ─────────────────────────────────
function toImportPath(filePath) {
    const rel = path.relative(path.join(ROOT, 'src'), filePath).replace(/\\/g, '/').replace(/\.tsx$/, '');
    return `@/${rel}`;
}

// ── Batch array into chunks ───────────────────────────────────────────
function batch(arr, size) {
    const batches = [];
    for (let i = 0; i < arr.length; i += size) {
        batches.push(arr.slice(i, i + size));
    }
    return batches;
}

// ── Write a test file ─────────────────────────────────────────────────
function writeTest(filename, content) {
    const outPath = path.join(TEST_DIR, filename);
    fs.writeFileSync(outPath, content, 'utf-8');
    return outPath;
}

