// ── 12. FILE SIZE & COMPLEXITY TRACKING ───────────────────────────────
function generateComplexityTests() {
    const complexity = [];
    for (const [code, entry] of entries) {
        const absPath = path.resolve(ROOT, '../../', entry.file);
        try {
            const content = fs.readFileSync(absPath, 'utf-8');
            const lines = content.split('\n').length;
            const bytes = Buffer.byteLength(content);
            const hooks = (content.match(/use[A-Z]\w+/g) || []).length;
            const states = (content.match(/useState/g) || []).length;
            const effects = (content.match(/useEffect/g) || []).length;
            complexity.push({
                code, label: entry.label, type: entry.type,
                lines, bytes, hooks, states, effects,
            });
        } catch { /* skip */ }
    }

    const tests = complexity.map(p => {
        return `    it('${p.code}: ${p.label} — ${p.lines} lines, ${p.hooks} hooks, ${p.states} states, ${p.effects} effects', () => {
        // Pages over 500 lines should be flagged for refactoring
        expect(${p.lines}).toBeLessThan(1000);
    });`;
    }).join('\n\n');

    const avgLines = Math.round(complexity.reduce((s, p) => s + p.lines, 0) / complexity.length);
    const maxLines = Math.max(...complexity.map(p => p.lines));
    const heaviest = complexity.find(p => p.lines === maxLines);

    const content = `/**
 * Auto-generated File Complexity Tests
 * Tracks LOC, hooks, state, effects per page. Flags files > 500 lines.
 * Avg: ${avgLines} lines. Max: ${maxLines} lines (${heaviest?.code}).
 * Generated by scripts/generate-tests.mjs
 */
import { describe, it, expect } from 'vitest';

describe('File Complexity (${complexity.length} pages, avg ${avgLines} LOC)', () => {
    it('average page should be under 300 lines', () => {
        expect(${avgLines}).toBeLessThan(500);
    });

${tests}
});
`;
    writeTest('FileComplexity.test.ts', content);
    totalFiles++;
    totalTests += complexity.length + 1;
    console.log(`  ✅ File Complexity: 1 file, ${complexity.length + 1} tests`);
}

