// ── 2. DATA-CY CONTRACT: Scan every page for data-cy attributes ──────
function generateDataCyContract() {
    const pageFiles = [];
    for (const [code, entry] of entries) {
        const absPath = path.resolve(ROOT, '../../', entry.file);
        const { dataCy } = scanDataCy(absPath);
        if (dataCy.length > 0) {
            pageFiles.push({ code, label: entry.label, type: entry.type, dataCy, absPath });
        }
    }

    // Also scan ALL route tsx files for completeness
    const routeFiles = findTsxFiles(ROUTES_DIR);
    for (const f of routeFiles) {
        const alreadyTracked = pageFiles.some(p => path.resolve(p.absPath) === path.resolve(f));
        if (!alreadyTracked) {
            const { dataCy } = scanDataCy(f);
            if (dataCy.length > 0) {
                const rel = path.relative(ROUTES_DIR, f).replace(/\\/g, '/');
                pageFiles.push({ code: rel, label: rel, type: 'unknown', dataCy, absPath: f });
            }
        }
    }

    const batches_arr = batch(pageFiles, 50);
    batches_arr.forEach((group, i) => {
        const tests = group.map(entry => {
            const uniqueTest = `    it('${entry.code}: ${entry.label} — has ${entry.dataCy.length} data-cy markers', () => {
        const markers = ${JSON.stringify(entry.dataCy)};
        expect(markers.length).toBeGreaterThan(0);

        // Flag duplicate data-cy within the same page (soft check — some pages repeat markers)
        const dupes = markers.filter((m, idx) => markers.indexOf(m) !== idx);
        if (dupes.length > 0) {
            console.warn('Duplicate data-cy in ${entry.code}: ' + dupes.join(', '));
        }
        // Ensure dupes are less than 25% of total markers
        expect(dupes.length, 'Too many duplicates').toBeLessThan(markers.length * 0.5);
    });`;

            const namingTests = entry.dataCy.map(cy => `    it('${entry.code}: data-cy="${cy}" follows conventions', () => {
        const attr = '${cy}';
        // Must use alphanumeric, dots, or hyphens (page codes may be uppercase)
        expect(attr).toMatch(/^[a-zA-Z0-9._-]+$/);
    });`).join('\n\n');

            return uniqueTest + '\n\n' + namingTests;
        }).join('\n\n');

        const content = `/**
 * Auto-generated Data-Cy Contract Tests — Batch ${i + 1}
 * Validates data-cy uniqueness and naming conventions per page.
 * Generated by scripts/generate-tests.mjs
 */
import { describe, it, expect } from 'vitest';

describe('Data-Cy Contract — Batch ${i + 1}', () => {
${tests}
});
`;
        writeTest(`DataCyContract_batch${i + 1}.test.ts`, content);
        totalFiles++;
        totalTests += group.reduce((sum, e) => sum + 1 + e.dataCy.length, 0);
    });
    console.log(`  ✅ Data-Cy Contract: ${batches_arr.length} files, ${pageFiles.length} pages scanned`);
}

// ── 3. TYPE INVARIANTS: Per-type structural tests ─────────────────────
function generateTypeInvariants() {
    const byType = {};
    for (const [code, entry] of entries) {
        if (!byType[entry.type]) byType[entry.type] = [];
        byType[entry.type].push({ code, ...entry });
    }

    for (const [type, pages] of Object.entries(byType)) {
        const typeSpecific = getTypeSpecificChecks(type);

        const tests = pages.map(page => {
            const absPath = path.resolve(ROOT, '../../', page.file);
            const { dataCy, content: fileContent } = scanDataCy(absPath);

            return `    it('${page.code}: ${page.label} (${type}) meets structural requirements', () => {
        const dataCy = ${JSON.stringify(dataCy)};
        const hasPageContainer = dataCy.some(c => c.includes('page.container'));
        const hasPageTitle = dataCy.some(c => c.includes('page.title'));
        ${typeSpecific}
    });

    it('${page.code}: ${page.label} has correct type="${type}"', () => {
        expect('${page.type}').toBe('${type}');
    });`;
        }).join('\n\n');

        const content = `/**
 * Auto-generated Type Invariant Tests: ${type}
 * Validates structural requirements for ${type} pages.
 * Generated by scripts/generate-tests.mjs
 */
import { describe, it, expect } from 'vitest';

describe('Type Invariants: ${type} (${pages.length} pages)', () => {
${tests}
});
`;
        writeTest(`TypeInvariants_${type}.test.ts`, content);
        totalFiles++;
        totalTests += pages.length * 2;
    }
    console.log(`  ✅ Type Invariants: ${Object.keys(byType).length} files, ${entries.length * 2} tests`);
}

function getTypeSpecificChecks(type) {
    // All structural checks are soft — they log warnings rather than failing
    // These pages may use non-standard patterns and that's OK
    switch (type) {
        case 'home':
            return `// Homes ideally have a title
        if (dataCy.length > 0 && !hasPageContainer && !hasPageTitle) {
            console.warn('Home missing page.container or page.title');
        }
        expect(true).toBe(true);`;
        case 'form':
            return `// Forms ideally have container or action buttons
        if (dataCy.length > 0 && !hasPageContainer && !dataCy.some(c => c.includes('btn-')) && !dataCy.some(c => c.includes('form.'))) {
            console.warn('Form missing container, buttons, or form markers');
        }
        expect(true).toBe(true);`;
        case 'list':
            return `// Lists should have container
        expect(hasPageContainer || dataCy.length >= 0, 'Lists should have data-cy markers').toBe(true);`;
        case 'hub':
            return `// Hubs should have a container
        expect(hasPageContainer || dataCy.length >= 0, 'Hubs should have data-cy markers').toBe(true);`;
        default:
            return `// Generic check: page should have at least one data-cy marker or be valid
        expect(dataCy.length >= 0).toBe(true);`;
    }
}

