"""Single localization catalog -> deterministic Dart, with key/placeholder parity checks."""
import json,re,sys
from pathlib import Path
source=Path('packages/contracts/locales/admin.json')
def unique(pairs):
 result={}
 for key,value in pairs:
  if key in result:raise ValueError('Duplicate localization key: '+key)
  result[key]=value
 return result
catalogs=json.loads(source.read_text(),object_pairs_hook=unique)
assert set(catalogs)=={'en','es','fr'}
for lang,values in catalogs.items():
 assert set(values)==set(catalogs['en']),lang+' key mismatch'
 for key,value in values.items():
  assert isinstance(value,str) and value.strip(),lang+' empty '+key
  assert set(re.findall(r'\{(\w+)\}',value))==set(re.findall(r'\{(\w+)\}',catalogs['en'][key])),lang+' placeholder mismatch '+key
# JSON quoting is valid Dart after escaping interpolation.
def dart(value):return json.dumps(value,ensure_ascii=False).replace('$','\\$')
text='// Generated by scripts/generate-app-localizations.py; edit the shared JSON catalog.\nconst appCatalogs = <String, Map<String, String>>{\n'
for lang,values in catalogs.items():
 text+='  '+dart(lang)+': {\n'+''.join('    '+dart(k)+': '+dart(v)+',\n' for k,v in values.items())+'  },\n'
text+='};\n'
output=Path('packages/primecare_ui/lib/src/localization/app_catalogs.dart')
if '--check' in sys.argv:
 assert output.read_text()==text,'Generated localization file is stale'
else:output.write_text(text)
print(f'PASS: {len(catalogs["en"])} keys in EN/ES/FR; placeholders and generated catalog verified')
