#!/usr/bin/env python3
"""Generate shared generative Material adapters from the pinned SDK signature inventory."""
import argparse,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
SPEC=ROOT/'scripts/shared-material-controls-api-3.41.5.json'
TARGET=ROOT/'packages/primecare_ui_foundation/lib/src/prime_material_controls.dart'
def generate():
 rows=json.loads(SPEC.read_text());out="import 'package:flutter/material.dart';\n\n// Generated by scripts/generate-shared-material-controls.py from Flutter 3.41.5.\n// Super parameters inherit the exact SDK parameter types and defaults.\n"
 for row in rows:
  cls=row['name'];shared=row.get('shared_name','Prime'+cls);generic='<T>' if row['generic'] else '';out+=f'\n/// Shared {cls} using the active Material theme and SDK behavior.\nclass {shared}{generic} extends {cls}{generic} {{\n'
  for ctor in row['constructors']:
   name=ctor['name'];out+='  '+('const ' if ctor['const'] else '')+shared+name+'({\n'
   for p in ctor['parameters']:out+='    '+('required ' if p['required'] else '')+'super.'+p['name']+',\n'
   out+='  })'+(' : super'+name+'()' if name else '')+';\n'
  if cls=='FilledButton':out+='  static const styleFrom = FilledButton.styleFrom;\n'
  out+='}\n'
 return out
def main():
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args();expected=generate()
 if a.check:
  if not TARGET.exists() or TARGET.read_text()!=expected:raise SystemExit('Shared controls differ from pinned SDK signature inventory')
 else:TARGET.write_text(expected)
if __name__=='__main__':main()
