"""Validate en/es/fr UI catalogs and generate their shared Flutter runtime data."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
DIRECTORY = ROOT / 'packages/primecare_ui/lib/src/localization/admin_role_carousel'
OUTPUT = DIRECTORY.parent / 'admin_role_carousel_catalog.dart'
SCREEN = ROOT / 'packages/primecare_ui/lib/src/screens/admin/admin_role_carousel_screen.dart'
PARAMETER = re.compile(r'\{([a-zA-Z][a-zA-Z0-9_]*)\}')


def validate():
    catalogs = {locale: json.loads((DIRECTORY / f'{locale}.json').read_text())
                for locale in ('en', 'es', 'fr')}
    english = catalogs['en']
    for locale, entries in catalogs.items():
        if set(entries) != set(english):
            raise ValueError(f'{locale}: missing/extra keys: {set(entries) ^ set(english)}')
        for key, value in entries.items():
            if not isinstance(value, str) or not value.strip():
                raise ValueError(f'{locale}.{key}: empty or non-text value')
            if set(PARAMETER.findall(value)) != set(PARAMETER.findall(english[key])):
                raise ValueError(f'{locale}.{key}: interpolation parameters differ')
    source = SCREEN.read_text()
    referenced = {key for key in re.findall(r"_t\('([^']+)'", source) if '$' not in key}
    if referenced - set(english):
        raise ValueError(f'Missing referenced keys: {referenced - set(english)}')
    literal = re.compile(r'''\b(?:Text\s*\(\s*|(?:hintText|labelText|tooltip|title|subtitle)\s*:\s*)(['"])(.*?)\1''')
    remaining = [match.group(2) for match in literal.finditer(source) if '$' not in match.group(2)]
    if remaining:
        raise ValueError(f'Unlocalized UI literals remain: {remaining}')
    return catalogs


def render(catalogs):
    lines = ['// Generated by scripts/check-admin-localization.py. Edit the en/es/fr JSON sources.',
             'const adminRoleCarouselCatalog = <String, Map<String, String>>{']
    for locale, entries in catalogs.items():
        lines.append(f'  "{locale}": {{')
        for key, value in entries.items():
            # JSON quoting is valid for these Dart strings; escape Dart interpolation.
            encoded = json.dumps(value, ensure_ascii=False).replace('$', r'\$')
            lines.append(f'    {json.dumps(key)}: {encoded},')
        lines.append('  },')
    lines.append('};')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    options = parser.parse_args()
    catalogs = validate()
    expected = render(catalogs)
    if options.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            raise SystemExit('Generated catalog drift: run python3 scripts/check-admin-localization.py')
    else:
        OUTPUT.write_text(expected)
    print(f'Admin Role Carousel: {len(catalogs["en"])} keys validated in en/es/fr; parameters match.')
