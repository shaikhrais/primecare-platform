import {readFile,writeFile} from 'node:fs/promises';
const guide=JSON.parse(await readFile('packages/shared/src/getting-started-guide.json','utf8'));
const translations=JSON.parse(await readFile('packages/shared/src/getting-started-guide-i18n.json','utf8'));
if(!Array.isArray(guide.steps) || !guide.steps.length || Object.keys(translations).sort().join(',')!=='es,fr') throw Error('Invalid guide or supported languages');
for(const language of ['fr','es']) {
  const items=translations[language];
  if(!Array.isArray(items)||items.length!==guide.steps.length) throw Error(`Invalid ${language} lesson count`);
  for(let i=0;i<items.length;i++) {
    const item=items[i], original=guide.steps[i];
    if(!item||Object.keys(item).sort().join(',')!=='body,check,domains,title' ||
       ['title','body','check'].some(key=>typeof item[key]!=='string'||!item[key].trim()) ||
       !Array.isArray(item.domains)||item.domains.length!==original.domains.length ||
       item.domains.some(value=>typeof value!=='string'||!value.trim())) throw Error(`Invalid ${language} lesson ${i+1}`);
  }
}
const source='// Generated by scripts/generate-getting-started-guide.mjs from the shared guide.\nconst gettingStartedSteps = <Map<String, dynamic>>'+JSON.stringify(guide.steps,null,2)+';\n\nconst gettingStartedTranslations = <String, List<Map<String, dynamic>>>'+JSON.stringify(translations,null,2)+';\n';
const target='packages/primecare_ui/lib/src/features/training/getting_started_catalog.g.dart';
if(process.argv.includes('--check')) {
  if(await readFile(target,'utf8')!==source) throw Error(`Stale generated guide: ${target}`);
} else await writeFile(target,source);
