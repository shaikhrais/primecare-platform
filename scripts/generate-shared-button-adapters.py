#!/usr/bin/env python3
"""Generate cycle-free button delegates from the pinned CI SDK's public API."""
import argparse
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
API=json.loads(Path(__file__).with_name('shared-button-api-3.41.5.json').read_text())
COMMON=[('VoidCallback?', 'onPressed'),('VoidCallback?','onLongPress'),
 ('ValueChanged<bool>?','onHover'),('ValueChanged<bool>?','onFocusChange'),
 ('ButtonStyle?','style'),('FocusNode?','focusNode'),('bool','autofocus'),
 ('Clip?','clipBehavior'),('WidgetStatesController?','statesController')]


def generate():
    out="// Generated by scripts/generate-shared-button-adapters.py.\n// Public API pinned to Flutter 3.41.5; delegates retain SDK theme and behavior.\nimport 'package:flutter/material.dart';\n\n"
    for kind,entry in API.items():
        name='Prime'+kind
        out+='/// Shared '+kind+' delegate; all styling remains inherited or caller supplied.\n'
        out+='class '+name+' extends StatelessWidget {\n'
        for typ,field in COMMON:out+='  final '+typ+' '+field+';\n'
        out+='  final Widget? child;\n  final Widget? icon;\n  final Widget? label;\n  final IconAlignment? iconAlignment;\n  final bool _iconVariant;\n\n'
        out+='  const '+name+'({super.key, required this.onPressed,\n'
        out+='    this.onLongPress, this.onHover, this.onFocusChange, this.style,\n'
        out+='    this.focusNode, this.autofocus = false, this.clipBehavior,\n'
        out+='    this.statesController, required this.child,\n'
        out+='  }) : icon = null, label = null, iconAlignment = null, _iconVariant = false;\n\n'
        out+='  '+name+'.icon({super.key, required this.onPressed,\n'
        out+='    this.onLongPress, this.onHover, this.onFocusChange, this.style,\n'
        out+='    this.focusNode, this.autofocus = false, this.clipBehavior = Clip.none,\n'
        out+='    this.statesController, this.icon, required Widget label, this.iconAlignment,\n'
        out+='  }) : child = null, label = label, _iconVariant = true;\n\n'
        out+='  static ButtonStyle styleFrom({\n'
        for p in entry['styleParameters']:out+='    '+p['type']+' '+p['name']+',\n'
        out+='  }) => '+kind+'.styleFrom(\n'
        for p in entry['styleParameters']:out+='    '+p['name']+': '+p['name']+',\n'
        out+='  );\n\n  @override\n  Widget build(BuildContext context) {\n'
        out+='    if (_iconVariant) {\n      return '+kind+'.icon(\n'
        for _,field in COMMON:out+='        '+field+': '+field+',\n'
        out+='        icon: icon, label: label!, iconAlignment: iconAlignment,\n      );\n    }\n'
        out+='    return '+kind+'(\n'
        for _,field in COMMON:out+='      '+field+': '+field+',\n'
        out+='      child: child,\n    );\n  }\n}\n\n'
    return out.rstrip()+'\n'


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    target=ROOT/'packages/primecare_ui_foundation/lib/src/prime_material_buttons.dart';value=generate()
    if a.check:
        if target.read_text()!=value:raise SystemExit('Shared button adapter drift')
    else:target.write_text(value)
    print('Three shared button delegates match the pinned public API')
